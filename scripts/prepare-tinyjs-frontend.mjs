#!/usr/bin/env node

/**
 * @file scripts/prepare-tinyjs-frontend.mjs
 * @description Builds the Next.js static export (`out/`) and relativizes root-relative
 * asset references (`/_next/`, `/favicon.ico`, `/icon*`, `@font-face` media URLs, and
 * Webpack's `r.p` publicPath) so the exported frontend runs directly over `file://`
 * inside TinyJS's native Windows WebView2, macOS WKWebView, and Linux WebKitGTK launchers.
 */

import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const OUT_DIR = path.resolve(process.cwd(), 'out');

function relativizeHtml(html) {
  return html
    .replace(
      /(href|src)="\/(_next\/|images\/|favicon\.ico|icon|apple-|manifest\.webmanifest)/g,
      '$1="./$2'
    )
    .replace(/"\/_next\/static\//g, '"./_next/static/')
    .replace(/\\"\/_next\/static\//g, '\\"./_next/static/')
    .replace(
      /\\"href\\":\\"\/(favicon\.ico|icon|apple-|manifest\.webmanifest)/g,
      '\\"href\\":\\"./$1'
    );
}

function relativizeCss(css) {
  return css.replace(/url\(\s*(['"]?)\/_next\/static\/media\//g, 'url($1../media/');
}

function relativizeWebpackJs(js) {
  return js.replace(/\.p="\/_next\/"/g, '.p="./_next/"');
}

function walkFiles(dir, predicate) {
  if (!fs.existsSync(dir)) {
    return [];
  }

  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...walkFiles(fullPath, predicate));
    } else if (predicate(fullPath)) {
      results.push(fullPath);
    }
  }
  return results;
}

console.log('==> [TinyJS] Building Next.js static export into out/...');
execSync('npx next build', {
  stdio: 'inherit',
  env: {
    ...process.env,
    NODE_ENV: 'production',
    NEXT_EXPORT: 'true',
    NEXT_PUBLIC_BASE_PATH: '',
  },
});

if (!fs.existsSync(path.join(OUT_DIR, 'index.html'))) {
  throw new Error('Expected out/index.html was not generated by next build.');
}

const htmlFiles = walkFiles(OUT_DIR, (p) => p.endsWith('.html'));
for (const filePath of htmlFiles) {
  const original = fs.readFileSync(filePath, 'utf8');
  const updated = relativizeHtml(original);
  if (updated !== original) {
    fs.writeFileSync(filePath, updated, 'utf8');
  }
}

const cssDir = path.join(OUT_DIR, '_next', 'static', 'css');
for (const filePath of walkFiles(cssDir, (p) => p.endsWith('.css'))) {
  const original = fs.readFileSync(filePath, 'utf8');
  const updated = relativizeCss(original);
  if (updated !== original) {
    fs.writeFileSync(filePath, updated, 'utf8');
  }
}

const chunksDir = path.join(OUT_DIR, '_next', 'static', 'chunks');
for (const filePath of walkFiles(
  chunksDir,
  (p) => path.basename(p).startsWith('webpack-') && p.endsWith('.js')
)) {
  const original = fs.readFileSync(filePath, 'utf8');
  const updated = relativizeWebpackJs(original);
  if (updated !== original) {
    fs.writeFileSync(filePath, updated, 'utf8');
  }
}

console.log(
  `==> [TinyJS] Relativized ${htmlFiles.length} HTML files, CSS font URLs, and Webpack runtime for file:// WebView2 packaging.`
);

await import('./generate-delta-manifest.mjs');

